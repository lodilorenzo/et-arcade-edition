"""Unified source-built ET launcher: Online or local matches with bots/split-screen."""
import argparse
from pathlib import Path
import re
import shutil
import subprocess

from play_online import prepare_online, ONLINE_SETTINGS
from smoke_server import ROOT, PLAY_VIDEO_SETTINGS, has_play_video_defaults, play_config


def prepare_game(modules, home):
    engine = modules / "et.exe"
    names = ("qagame", "cgame", "cgame2", "cgame3", "cgame4", "ui")
    for name in names:
        if not (modules / f"{name}_mp_x86.dll").is_file():
            raise SystemExit(f"Build {modules} first (missing {name} module).")
    command = prepare_online(engine, home)
    shell = home / "et-rust"
    shell.mkdir(parents=True, exist_ok=True)
    first = not play_config(shell).exists()
    if first:
        previous = modules / "smoke/slice-play-client/oasis/et-rust"
        source = previous if play_config(previous).exists() else home / "etmain"
        if (source / "profiles").exists():
            shutil.copytree(source / "profiles", shell / "profiles", dirs_exist_ok=True)
        if (source / "etconfig.cfg").exists():
            shutil.copy2(source / "etconfig.cfg", shell)
        # Preserve the chosen online nickname while retaining local controls/video.
        online = play_config(home / "etmain")
        saved = play_config(shell)
        if online.exists() and saved.exists():
            name = re.search(r'^seta name "[^\r\n]*"$', online.read_text(encoding="latin-1"), re.M)
            if name:
                with saved.open("a", encoding="latin-1") as config:
                    config.write(f'\n{name[0]}\n')
    for name in names:
        shutil.copy2(modules / f"{name}_mp_x86.dll", shell)
    shutil.copytree(ROOT / "native/ui", shell / "ui", dirs_exist_ok=True)
    settings = dict(ONLINE_SETTINGS)
    # Online uses its own one/four-instance selector; retain the local player selector.
    del settings["cl_splitScreen"]
    settings.update(ui_rustSlice="1", omnibot_path=str((ROOT / "runtime/omnibot").resolve()), ui_rustMonitorWidth=PLAY_VIDEO_SETTINGS["r_customwidth"],
                    ui_rustMonitorHeight=PLAY_VIDEO_SETTINGS["r_customheight"],
                    ui_rustMonitorRefresh=PLAY_VIDEO_SETTINGS["r_displayRefresh"])
    config = []
    saved = play_config(shell)
    if saved == shell / "etconfig.cfg" and saved.exists():
        config.append("exec etconfig.cfg")
    if not has_play_video_defaults(shell):
        settings.update(PLAY_VIDEO_SETTINGS)
        config.append('seta et_rustVideoVersion "1"')
    config.extend(f'set {key} "{value}"' for key, value in settings.items())
    (shell / "autoexec.cfg").write_text("\n".join(config) + "\n", encoding="ascii")
    command[-1] = "et-rust"
    command += ["+set", "et_unified", "1"]
    return command


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--modules", type=Path, default=ROOT / "build/slice/Release")
    parser.add_argument("--home", type=Path, default=ROOT / "output/online")
    args = parser.parse_args()
    home = args.home.resolve()
    command = prepare_game(args.modules.resolve(), home)
    if len(subprocess.list2cmdline(command[1:]).encode("utf-8")) > 1023:
        raise SystemExit("Paths exceed ET's startup limit; use a shorter --home path.")
    print("Play Online: server browser. Start Match: local humans + bots. Downloads execute trusted server mods.", flush=True)
    print(f"Shared identity: {home / 'etmain/etkey'} (generated by the engine if missing)", flush=True)
    raise SystemExit(subprocess.call(command, cwd=home))


if __name__ == "__main__":
    main()
